export default function BottomTabs({ active, onChange, onNew }) {
  const tabs = [
    { id: 'dashboard', label: 'Dashboard' },
    { id: 'sessions', label: 'Sessions' },
    { id: 'new', label: 'New', isNew: true },
    { id: 'settings', label: 'Settings' }
  ];
  return (
    <nav className="app-nav border-t border-bg-3 bg-bg-1/95 backdrop-blur" data-testid="tabs" aria-label="Primary">
      <div className="max-w-md mx-auto flex">
        {tabs.map(t => (
          <button
            key={t.id}
            type="button"
            className={`tab-button ${active === t.id ? 'tab-active' : ''}`}
            onClick={() => t.isNew ? onNew() : onChange(t.id)}
            data-testid={`tab-${t.id}`}
            aria-label={t.label}
            aria-current={active === t.id ? 'page' : undefined}
          >
            {t.isNew
              ? <div className="w-10 h-10 rounded-full bg-accent text-bg-0 flex items-center justify-center">{ICONS.new}</div>
              : ICONS[t.id]}
            <span>{t.label}</span>
          </button>
        ))}
      </div>
    </nav>
  );
}
